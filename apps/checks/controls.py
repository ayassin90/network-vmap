def controls_for(topics, cis=""):
    """{framework: [control ids]} for a list of objectives (+ the CIS benchmark item)."""
    out = {}
    for t in topics:
        for fw, ids in TOPICS.get(t, {}).items():
            if fw == "label":
                continue
            lst = out.setdefault(fw, [])
            for i in ids:
                if i not in lst:
                    lst.append(i)
    if cis:
        out["cis"] = [c.strip() for c in cis.split(",") if c.strip()]
    return {fw: sorted(ids, key=_sort_key) for fw, ids in out.items()}


def _sort_key(cid):
    import re
    return [int(p) if p.isdigit() else p for p in re.split(r"[.\-()]", cid) if p != ""]


def control_title(fw, cid):
    return CONTROLS.get(fw, {}).get(cid, "")


def sorted_controls(fw, ids):
    return sorted(ids, key=_sort_key)
